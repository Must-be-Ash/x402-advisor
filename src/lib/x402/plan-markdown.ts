import type { AdvisorPlan } from "./plan";

/** Render an AdvisorPlan as a shareable markdown spec. */
export function planToMarkdown(plan: AdvisorPlan): string {
  const lines: string[] = [];

  lines.push(`# x402 setup plan — ${plan.serviceName}`);
  lines.push("");
  lines.push(plan.summary);
  lines.push("");
  lines.push(`**Network:** \`${plan.network}\``);
  lines.push("");

  lines.push("## Endpoints");
  lines.push("");
  lines.push("| Endpoint | Scheme | Extensions | Price | Why |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const e of plan.endpoints) {
    const ep = `\`${e.method} ${e.path}\``;
    const ext = e.extensions.length ? e.extensions.join(", ") : "—";
    const why = e.schemeNote.replace(/\n+/g, " ");
    lines.push(
      `| ${ep} | ${e.schemeLabel} | ${ext} | ${e.priceHint || "—"} | ${why} |`,
    );
  }
  lines.push("");

  if (plan.glossary.length) {
    lines.push("## What these terms mean");
    lines.push("");
    for (const g of plan.glossary) lines.push(`- **${g.term}** — ${g.explanation}`);
    lines.push("");
  }

  if (plan.nextSteps.length) {
    lines.push("## Next steps");
    lines.push("");
    plan.nextSteps.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
    lines.push("");
  }

  if (plan.caveats.length) {
    lines.push("## Caveats");
    lines.push("");
    for (const c of plan.caveats) lines.push(`- ${c}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("_Generated by the x402 setup advisor._");
  return lines.join("\n");
}
